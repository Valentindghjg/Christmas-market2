--!strict
return function(t)
	local PlotService = require(
		game:GetService("ServerScriptService")
			:WaitForChild("Server")
			:WaitForChild("Services")
			:WaitForChild("PlotService")
	)
	local expect = t.expect

	-- Each save (holder) receives one distinct plot and may safely reclaim it.
	t.test("allocates distinct plots", function()
		local plots = PlotService.new({ "PlotA", "PlotB" })
		local first = plots:claim("save:42_a")
		local second = plots:claim("save:77_b")
		expect.equal(first, "PlotA")
		expect.equal(second, "PlotB")
		expect.equal(plots:claim("save:42_a"), "PlotA")
		expect.truthy(plots:owns("save:42_a", "PlotA"))
		expect.falsy(plots:owns("save:42_a", "PlotB"))
		expect.equal(plots:getPlot("save:77_b"), "PlotB")
		expect.equal(plots:freeCount(), 0)
		local none, reason = plots:claim("save:99_c")
		expect.equal(none, nil)
		expect.equal(reason, "NoPlotsAvailable")
		local invalid, invalidReason = plots:claim("")
		expect.equal(invalid, nil)
		expect.equal(invalidReason, "InvalidHolder")
	end)

	-- Released plots become available without leaking ownership.
	t.test("releases plots on leave", function()
		local plots = PlotService.new({ "PlotA" })
		expect.equal(plots:claim("save:42_a"), "PlotA")
		expect.truthy(plots:release("save:42_a"))
		expect.falsy(plots:release("save:42_a"))
		expect.equal(plots:getPlot("save:42_a"), nil)
		expect.equal(plots:claim("save:77_b"), "PlotA")
	end)

	-- A switched save keeps its plot when it is free; otherwise config order decides.
	t.test("prefers the requested free plot", function()
		local plots = PlotService.new({ "PlotA", "PlotB", "PlotC" })
		expect.equal(plots:claim("save:1_a", "PlotB"), "PlotB")
		expect.equal(plots:claim("save:2_b", "PlotB"), "PlotA")
		expect.equal(plots:claim("save:3_c", "PlotX"), "PlotC")
		expect.equal(plots:freeCount(), 0)
	end)

	-- CM2-G15: the liked lot's save comes from the plot claim.
	t.test("holderOf names the claimant", function()
		local plots = PlotService.new({ "PlotA", "PlotB" })
		expect.equal(plots:claim("save:42_a"), "PlotA")
		expect.equal(plots:holderOf("PlotA"), "save:42_a")
		expect.equal(plots:holderOf("PlotB"), nil)
		expect.equal(plots:holderOf("PlotZ"), nil)
		expect.equal(plots:holderOf(1), nil)
		expect.equal(plots:holderOf(nil), nil)
		expect.truthy(plots:release("save:42_a"))
		expect.equal(plots:holderOf("PlotA"), nil)
	end)

	-- CM2-PP: the plot picker claims exactly the chosen plot when it is free.
	t.test("claimExact claims a free plot and refuses a taken or unknown one", function()
		local plots = PlotService.new({ "Plot_01", "Plot_02", "Plot_03" })
		expect.equal(plots:claimExact("save:42_a", "Plot_02"), "Plot_02")
		local again, againError = plots:claimExact("save:42_a", "Plot_03")
		expect.equal(again, "Plot_02")
		expect.equal(againError, nil)
		local taken, takenError = plots:claimExact("save:77_b", "Plot_02")
		expect.equal(taken, nil)
		expect.equal(takenError, "PlotTaken")
		local unknown, unknownError = plots:claimExact("save:77_b", "Plot_09")
		expect.equal(unknown, nil)
		expect.equal(unknownError, "UnknownPlot")
		expect.equal(plots:getPlot("save:77_b"), nil)
		expect.equal(plots:holderOf("Plot_02"), "save:42_a")
		expect.equal(plots:holderOf("Plot_01"), nil)
		expect.equal(plots:holderOf("Plot_03"), nil)
		expect.equal(plots:freeCount(), 2)
	end)

	t.test("plotIds and has list the configured plots", function()
		local plots = PlotService.new({ "Plot_02", "Plot_01", "Plot_03" })
		local ids = plots:plotIds()
		expect.equal(#ids, 3)
		expect.equal(ids[1], "Plot_02")
		expect.equal(ids[2], "Plot_01")
		expect.equal(ids[3], "Plot_03")
		ids[1] = "Plot_09"
		table.insert(ids, "Plot_04")
		local fresh = plots:plotIds()
		expect.equal(#fresh, 3)
		expect.equal(fresh[1], "Plot_02")
		expect.truthy(plots:has("Plot_01"))
		expect.falsy(plots:has("Plot_09"))
		expect.falsy(plots:has(1))
		expect.falsy(plots:has(nil))
	end)
end
